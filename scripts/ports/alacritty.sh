# shellcheck shell=bash
# Alacritty color files (TOML), one per variant.
# Output: ports/alacritty/terminal-noir.toml, ports/alacritty/terminal-noir-paper.toml

build_alacritty() {
    local v file
    for v in dark light; do
        file="terminal-noir$([ "$v" = light ] && echo -paper || true).toml"
        jq -r --arg v "$v" '
            .variants[$v] as $c
            | ["black","red","green","yellow","blue","magenta","cyan","white"] as $n
            | def kv($k; $x): "\($k) = \"\($x)\"";
            "# Terminal Noir (\($v)) for Alacritty. https://terminalnoir.web.app",
            "# Generated by scripts/build from palette/palette.json.",
            "",
            "[colors.primary]",
            kv("background"; $c.surface.base),
            kv("foreground"; $c.text.primary),
            kv("dim_foreground"; $c.text.muted),
            kv("bright_foreground"; $c.text.primary),
            "",
            "[colors.cursor]",
            kv("text"; $c.accent.onPrimary),
            kv("cursor"; $c.accent.primary),
            "",
            "[colors.vi_mode_cursor]",
            kv("text"; $c.accent.onPrimary),
            kv("cursor"; $c.accent.info),
            "",
            "[colors.selection]",
            kv("text"; $c.text.primary),
            kv("background"; $c.surface.selection),
            "",
            "[colors.search.matches]",
            kv("foreground"; $c.accent.onPrimary),
            kv("background"; $c.accent.warning),
            "",
            "[colors.search.focused_match]",
            kv("foreground"; $c.accent.onPrimary),
            kv("background"; $c.accent.primary),
            "",
            "[colors.footer_bar]",
            kv("foreground"; $c.text.primary),
            kv("background"; $c.surface.elevated),
            "",
            "[colors.hints.start]",
            kv("foreground"; $c.accent.onPrimary),
            kv("background"; $c.accent.primary),
            "",
            "[colors.hints.end]",
            kv("foreground"; $c.accent.onPrimary),
            kv("background"; $c.accent.warning),
            "",
            "[colors.normal]",
            ($n[] as $k | kv($k; $c.ansi.normal[$k])),
            "",
            "[colors.bright]",
            ($n[] as $k | kv($k; $c.ansi.bright[$k]))' "$PALETTE" > "$OUT/ports/alacritty/$file"
    done
}

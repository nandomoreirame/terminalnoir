# shellcheck shell=bash
# fish theme with [light] and [dark] sections; fish picks the one that matches
# the terminal background. Output: ports/fish/terminal-noir.theme

build_fish() {
    jq -r --arg q "'" '
        def hex($x): $x | ltrimstr("#") | ascii_downcase;
        def section($v; $c):
            def k($name; $x): "\($name) \(hex($x))";
            def bg($name; $x): "\($name) --background=\(hex($x))";
            "[\($v)]",
            "# preferred_background: \(hex($c.surface.base))",
            k("fish_color_normal"; $c.text.primary),
            k("fish_color_command"; $c.accent.info),
            k("fish_color_keyword"; $c.accent.primary),
            k("fish_color_quote"; $c.accent.success),
            k("fish_color_redirection"; $c.accent.warning),
            k("fish_color_end"; $c.accent.warning),
            k("fish_color_operator"; $c.accent.warning),
            k("fish_color_error"; $c.accent.error),
            k("fish_color_param"; $c.text.primary),
            k("fish_color_option"; $c.ansi.bright.cyan),
            k("fish_color_escape"; $c.ansi.bright.cyan),
            k("fish_color_comment"; $c.text.muted),
            k("fish_color_autosuggestion"; $c.text.faint),
            k("fish_color_gray"; $c.text.faint),
            "fish_color_valid_path --underline",
            "fish_color_history_current --bold",
            bg("fish_color_selection"; $c.surface.selection),
            bg("fish_color_search_match"; $c.surface.selection),
            k("fish_color_cancel"; $c.accent.error),
            k("fish_color_cwd"; $c.accent.primary),
            k("fish_color_cwd_root"; $c.accent.error),
            k("fish_color_user"; $c.accent.success),
            k("fish_color_host"; $c.accent.info),
            k("fish_color_host_remote"; $c.accent.warning),
            k("fish_color_status"; $c.accent.error),
            k("fish_pager_color_progress"; $c.text.muted),
            "\(k("fish_pager_color_prefix"; $c.accent.primary)) --bold",
            k("fish_pager_color_completion"; $c.text.primary),
            k("fish_pager_color_description"; $c.text.muted),
            bg("fish_pager_color_selected_background"; $c.surface.elevated);
        "# name: \($q)Terminal Noir\($q)",
        "# url: \($q)https://terminalnoir.web.app\($q)",
        "# Generated by scripts/build from palette/palette.json.",
        "",
        section("light"; .variants.light),
        "",
        section("dark"; .variants.dark)' "$PALETTE" > "$OUT/ports/fish/terminal-noir.theme"
}

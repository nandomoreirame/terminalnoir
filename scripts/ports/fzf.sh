# shellcheck shell=bash
# fzf colors as a shell snippet (dark). Appends to any FZF_DEFAULT_OPTS the
# user already has. Output: ports/fzf/terminal-noir.sh

build_fzf() {
    local colors
    colors="$(jq -r '
        .variants.dark as $c
        | [ "bg:-1", "fg:\($c.text.primary)", "hl:\($c.accent.primary)",
            "bg+:\($c.surface.elevated)", "fg+:\($c.text.primary)", "hl+:\($c.accent.primary)",
            "gutter:-1", "info:\($c.text.muted)", "prompt:\($c.accent.primary)",
            "pointer:\($c.accent.primary)", "marker:\($c.accent.success)",
            "spinner:\($c.accent.primary)", "header:\($c.text.muted)",
            "border:\($c.surface.outline)", "separator:\($c.surface.outline)",
            "scrollbar:\($c.surface.outline)", "query:\($c.text.primary)" ]
        | join(",")' "$PALETTE")"

    cat > "$OUT/ports/fzf/terminal-noir.sh" <<EOF
# Terminal Noir for fzf. https://terminalnoir.web.app
# Generated by scripts/build from palette/palette.json.
# Source it from your shell rc. bg:-1 keeps the terminal background.
export FZF_DEFAULT_OPTS="\${FZF_DEFAULT_OPTS:+\$FZF_DEFAULT_OPTS }--color=$colors"
EOF
}

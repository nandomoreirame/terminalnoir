# shellcheck shell=bash
# Ghostty themes, one file per variant.
# Output: ports/ghostty/terminal-noir-{dark,light}

build_ghostty() {
    local v
    for v in dark light; do
        {
            printf '# Terminal Noir (%s) for Ghostty. https://terminalnoir.web.app\n' "$v"
            printf '# Generated by scripts/build from palette/palette.json.\n\n'
            jq -r --arg v "$v" '
                .variants[$v] as $c
                | ["black","red","green","yellow","blue","magenta","cyan","white"] as $n
                | ([range(0; 8) as $i | "palette = \($i)=\($c.ansi.normal[$n[$i]])"]
                   + [range(0; 8) as $i | "palette = \($i + 8)=\($c.ansi.bright[$n[$i]])"]
                   + ["background = \($c.surface.base)",
                      "foreground = \($c.text.primary)",
                      "cursor-color = \($c.accent.primary)",
                      "cursor-text = \($c.accent.onPrimary)",
                      "selection-background = \($c.surface.selection)",
                      "selection-foreground = \($c.text.primary)"])
                | .[] | ascii_downcase' "$PALETTE"
        } > "$OUT/ports/ghostty/terminal-noir-$v"
    done
}

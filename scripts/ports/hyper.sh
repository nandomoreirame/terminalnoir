# shellcheck shell=bash
# Hyper plugin: a decorateConfig that applies the dark variant, or the light one
# with `terminalNoir: { variant: 'paper' }` in .hyper.js.
# Output: ports/hyper/package.json, ports/hyper/index.js

build_hyper() {
    local variants
    variants="$(jq '
        def names: ["black","red","green","yellow","blue","magenta","cyan","white"];
        def cap: (.[:1] | ascii_upcase) + .[1:];
        def scheme($c): {
            background: $c.surface.base, foreground: $c.text.primary,
            cursor: $c.accent.primary, cursorAccent: $c.accent.onPrimary,
            selection: $c.surface.selection, border: $c.surface.border,
            tabs: $c.surface.raised, tabActive: $c.surface.base, muted: $c.text.muted, accent: $c.accent.primary,
            colors: ([names[] as $k | {key: $k, value: $c.ansi.normal[$k]}]
                + [names[] as $k | {key: "light\($k | cap)", value: $c.ansi.bright[$k]}] | from_entries)
        };
        {noir: scheme(.variants.dark), paper: scheme(.variants.light)}' "$PALETTE")"

    jq -n --arg version "$(jq -r .version "$PALETTE")" '{
        name: "hyper-terminal-noir",
        version: $version,
        description: "Terminal Noir for Hyper: cold near-black surfaces with one amber accent, and a Paper light variant.",
        main: "index.js",
        keywords: ["hyper", "hyper-theme", "terminal-noir"],
        homepage: "https://terminalnoir.web.app",
        license: "MIT"
    }' > "$OUT/ports/hyper/package.json"

    {
        printf "'use strict';\n"
        printf '// Terminal Noir for Hyper. https://terminalnoir.web.app\n'
        printf '// Generated by scripts/build from palette/palette.json.\n\n'
        printf 'const variants = %s;\n\n' "$variants"
        cat <<'JS'
exports.decorateConfig = (config) => {
  const name = config.terminalNoir && config.terminalNoir.variant === 'paper' ? 'paper' : 'noir';
  const c = variants[name];
  return Object.assign({}, config, {
    backgroundColor: c.background,
    foregroundColor: c.foreground,
    cursorColor: c.cursor,
    cursorAccentColor: c.cursorAccent,
    selectionColor: c.selection,
    borderColor: c.border,
    colors: c.colors,
    css: `${config.css || ''}
      .header_header, .tabs_list { background-color: ${c.tabs} !important; }
      .tab_tab { color: ${c.muted}; border-color: ${c.border} !important; }
      .tab_tab.tab_active { color: ${c.foreground}; background-color: ${c.tabActive}; }
      .tab_textActive .tab_textInner::before { content: ''; position: absolute; left: 0; right: 0; bottom: 0; height: 2px; background: ${c.accent}; }
    `,
  });
};
JS
    } > "$OUT/ports/hyper/index.js"
}

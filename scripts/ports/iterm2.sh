# shellcheck shell=bash
# iTerm2 color presets (plist), one file per variant. Components are sRGB reals.
# Output: ports/iterm2/Terminal Noir.itermcolors, ports/iterm2/Terminal Noir Paper.itermcolors

build_iterm2() {
    local v name
    for v in dark light; do
        name="Terminal Noir$([ "$v" = light ] && echo ' Paper' || true)"
        jq -r --arg v "$v" --arg name "$name" '
            .variants[$v] as $c
            | ["black","red","green","yellow","blue","magenta","cyan","white"] as $n
            | def byte($h; $i): $h[$i:$i + 2] | ascii_downcase | explode
                | map(if . >= 97 then . - 87 else . - 48 end) | .[0] * 16 + .[1];
              def real($k; $x): "\t\t<key>\($k) Component</key>\n\t\t<real>\($x)</real>";
              def color($k; $hex):
                "\t<key>\($k)</key>",
                "\t<dict>",
                real("Alpha"; 1),
                real("Blue"; byte($hex; 5) / 255),
                "\t\t<key>Color Space</key>\n\t\t<string>sRGB</string>",
                real("Green"; byte($hex; 3) / 255),
                real("Red"; byte($hex; 1) / 255),
                "\t</dict>";
            "<?xml version=\"1.0\" encoding=\"UTF-8\"?>",
            "<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">",
            "<!-- \($name) for iTerm2. https://terminalnoir.web.app -->",
            "<!-- Generated by scripts/build from palette/palette.json. -->",
            "<plist version=\"1.0\">",
            "<dict>",
            (range(0; 8) as $i | color("Ansi \($i) Color"; $c.ansi.normal[$n[$i]])),
            (range(0; 8) as $i | color("Ansi \($i + 8) Color"; $c.ansi.bright[$n[$i]])),
            color("Background Color"; $c.surface.base),
            color("Foreground Color"; $c.text.primary),
            color("Bold Color"; $c.text.primary),
            color("Cursor Color"; $c.accent.primary),
            color("Cursor Text Color"; $c.accent.onPrimary),
            color("Selection Color"; $c.surface.selection),
            color("Selected Text Color"; $c.text.primary),
            color("Link Color"; $c.accent.info),
            "</dict>",
            "</plist>"' "$PALETTE" > "$OUT/ports/iterm2/$name.itermcolors"
    done
}

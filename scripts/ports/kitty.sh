# shellcheck shell=bash
# kitty color themes, one per variant.
# Output: ports/kitty/terminal-noir.conf, ports/kitty/terminal-noir-paper.conf

build_kitty() {
    local v file
    for v in dark light; do
        file="terminal-noir$([ "$v" = light ] && echo -paper || true).conf"
        jq -r --arg v "$v" '
            .variants[$v] as $c
            | ["black","red","green","yellow","blue","magenta","cyan","white"] as $n
            | def kv($k; $x): "\($k) \($x)";
            "# vim:ft=kitty",
            "## name: Terminal Noir\(if $v == "light" then " Paper" else "" end)",
            "## author: Fernando Moreira",
            "## license: MIT",
            "## upstream: https://terminalnoir.web.app",
            "## blurb: Generated by scripts/build from palette/palette.json.",
            "",
            kv("foreground"; $c.text.primary),
            kv("background"; $c.surface.base),
            kv("selection_foreground"; $c.text.primary),
            kv("selection_background"; $c.surface.selection),
            "",
            kv("cursor"; $c.accent.primary),
            kv("cursor_text_color"; $c.accent.onPrimary),
            kv("url_color"; $c.accent.info),
            "",
            kv("active_border_color"; $c.accent.primary),
            kv("inactive_border_color"; $c.surface.outline),
            kv("bell_border_color"; $c.accent.warning),
            "",
            kv("active_tab_foreground"; $c.accent.onPrimary),
            kv("active_tab_background"; $c.accent.primary),
            kv("inactive_tab_foreground"; $c.text.muted),
            kv("inactive_tab_background"; $c.surface.elevated),
            kv("tab_bar_background"; $c.surface.raised),
            "",
            kv("mark1_foreground"; $c.accent.onPrimary),
            kv("mark1_background"; $c.accent.primary),
            kv("mark2_foreground"; $c.accent.onPrimary),
            kv("mark2_background"; $c.accent.info),
            kv("mark3_foreground"; $c.accent.onPrimary),
            kv("mark3_background"; $c.accent.success),
            "",
            (range(0; 8) as $i | kv("color\($i)"; $c.ansi.normal[$n[$i]])),
            (range(0; 8) as $i | kv("color\($i + 8)"; $c.ansi.bright[$n[$i]]))' "$PALETTE" > "$OUT/ports/kitty/$file"
    done
}

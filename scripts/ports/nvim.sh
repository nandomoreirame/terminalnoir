build_nvim() {
    local groups
    groups="$(jq -nc "$_nvim_groups")"
    mkdir -p "$OUT/ports/nvim/colors" "$OUT/ports/nvim/vim/colors"

    jq -r --argjson groups "$groups" '
        . as $p
        | ["black","red","green","yellow","blue","magenta","cyan","white"] as $n
        | def col($v; $path): $p.variants[$v] | getpath($path | split("."));
          def entry($v):
              .n as $name
              | if .link then "    [\"\(.n)\"] = { link = \"\(.link)\" },"
              else [ (if .fg then "fg = \"\(col($v; .fg))\"" else empty end),
                     (if .bg then "bg = \"\(col($v; .bg))\"" else empty end),
                     (if .sp then "sp = \"\(col($v; .sp))\"" else empty end),
                     ((.s // "") | split(",")[] | select(length > 0) | "\(.) = true") ]
                   | "    [\"\($name)\"] = { \(join(", ")) },"
              end;
          def variant($v):
              "  \($v) = {",
              "    groups = {",
              ($groups[] | entry($v)),
              "    },",
              "    terminal = {",
              ([range(0; 8) as $i | "\"\($p.variants[$v].ansi.normal[$n[$i]])\""]
               + [range(0; 8) as $i | "\"\($p.variants[$v].ansi.bright[$n[$i]])\""] | "      " + join(", ")),
              "    },",
              "  },";
        "-- Terminal Noir for Neovim. https://terminalnoir.web.app",
        "-- Generated by scripts/build from palette/palette.json.",
        "-- Picks the dark or light variant from vim.o.background.",
        "",
        "local variants = {",
        variant("dark"),
        variant("light"),
        "}",
        "",
        "vim.cmd(\"highlight clear\")",
        "if vim.fn.exists(\"syntax_on\") == 1 then",
        "  vim.cmd(\"syntax reset\")",
        "end",
        "vim.o.termguicolors = true",
        "vim.g.colors_name = \"terminal-noir\"",
        "",
        "local v = variants[vim.o.background == \"light\" and \"light\" or \"dark\"]",
        "for name, spec in pairs(v.groups) do",
        "  vim.api.nvim_set_hl(0, name, spec)",
        "end",
        "for i, color in ipairs(v.terminal) do",
        "  vim.g[\"terminal_color_\" .. (i - 1)] = color",
        "end"' "$PALETTE" > "$OUT/ports/nvim/colors/terminal-noir.lua"

    jq -r --argjson groups "$groups" '
        . as $p
        | ["black","red","green","yellow","blue","magenta","cyan","white"] as $n
        | def col($v; $path): $p.variants[$v] | getpath($path | split("."));
          def hi($v):
              if .link then "  hi! link \(.n) \(.link)"
              else "  hi \(.n)"
                   + " guifg=\(if .fg then col($v; .fg) else "NONE" end)"
                   + " guibg=\(if .bg then col($v; .bg) else "NONE" end)"
                   + (if .sp then " guisp=\(col($v; .sp))" else "" end)
                   + " gui=\(.s // "NONE") cterm=\(.s // "NONE")"
              end;
          def variant($v):
              ($groups[] | select(.n | startswith("@") | not) | hi($v)),
              "  let g:terminal_ansi_colors = [" + ([range(0; 8) as $i | "\"\($p.variants[$v].ansi.normal[$n[$i]])\""]
                  + [range(0; 8) as $i | "\"\($p.variants[$v].ansi.bright[$n[$i]])\""] | join(", ")) + "]";
        "\" Terminal Noir for Vim. https://terminalnoir.web.app",
        "\" Generated by scripts/build from palette/palette.json.",
        "\" Picks the dark or light variant from background; needs termguicolors.",
        "",
        "hi clear",
        "if exists(\"syntax_on\")",
        "  syntax reset",
        "endif",
        "let g:colors_name = \"terminal-noir\"",
        "",
        "if &background ==# \"light\"",
        variant("light"),
        "else",
        variant("dark"),
        "endif"' "$PALETTE" > "$OUT/ports/nvim/vim/colors/terminal-noir.vim"
}

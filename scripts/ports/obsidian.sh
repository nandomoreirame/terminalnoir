# shellcheck shell=bash
# Obsidian community theme (dark mode only): a theme folder with manifest.json
# and theme.css. Output: ports/obsidian/Terminal Noir/{manifest.json,theme.css}

build_obsidian() {
    local dir="$OUT/ports/obsidian/Terminal Noir"
    mkdir -p "$dir"

    jq '{
        name: .name,
        version: .version,
        minAppVersion: "1.0.0",
        author: "Fernando Moreira",
        authorUrl: .homepage
    }' "$PALETTE" > "$dir/manifest.json"

    jq -r --slurpfile syn "$SYNTAX" '
        .variants.dark as $c
        | def ref($p): $c | getpath($p | split("."));
          def tok($n): ref($syn[0].tokens[] | select(.name == $n) | .color);
          def chan($h; $i): $h | ltrimstr("#") | .[$i:$i + 2] | explode
              | map(if . >= 65 and . <= 70 then . - 55 elif . >= 97 then . - 87 else . - 48 end)
              | (.[0] * 16 + .[1]) / 255;
          def rgba($h; $a): "rgba(\(chan($h; 0) * 255 | round), \(chan($h; 2) * 255 | round), \(chan($h; 4) * 255 | round), \($a))";
          def hsl($h): [chan($h; 0), chan($h; 2), chan($h; 4)] as [$r, $g, $b]
              | ([$r, $g, $b] | max) as $mx | ([$r, $g, $b] | min) as $mn
              | (($mx + $mn) / 2) as $l | ($mx - $mn) as $d
              | (if $d == 0 then 0 else $d / (1 - ((2 * $l - 1) | fabs)) end) as $s
              | (if $d == 0 then 0
                 elif $mx == $r then (60 * (($g - $b) / $d) | if . < 0 then . + 360 else . end)
                 elif $mx == $g then 60 * (($b - $r) / $d + 2)
                 else 60 * (($r - $g) / $d + 4) end) as $hue
              | { h: ($hue | round), s: ($s * 100 | round), l: ($l * 100 | round) };
        hsl($c.accent.primary) as $acc
        | "/* Terminal Noir for Obsidian (dark). https://terminalnoir.web.app",
          " * Generated by scripts/build from palette/palette.json and palette/syntax.json. */",
          "",
          ".theme-dark {",
          "  --accent-h: \($acc.h);",
          "  --accent-s: \($acc.s)%;",
          "  --accent-l: \($acc.l)%;",
          "",
          "  --background-primary: \($c.surface.base);",
          "  --background-primary-alt: \($c.surface.raised);",
          "  --background-secondary: \($c.surface.raised);",
          "  --background-secondary-alt: \($c.surface.elevated);",
          "  --background-modifier-border: \($c.surface.border);",
          "  --background-modifier-border-hover: \($c.surface.outline);",
          "  --background-modifier-border-focus: \($c.surface.outline);",
          "  --background-modifier-hover: \($c.surface.elevated);",
          "  --background-modifier-active-hover: \($c.surface.elevated);",
          "  --background-modifier-form-field: \($c.surface.raised);",
          "",
          "  --text-normal: \($c.text.primary);",
          "  --text-muted: \($c.text.muted);",
          "  --text-faint: \($c.text.faint);",
          "  --text-accent: \($c.accent.primary);",
          "  --text-accent-hover: \($c.accent.warning);",
          "  --text-on-accent: \($c.accent.onPrimary);",
          "  --text-selection: \(rgba($c.surface.selection; 0.6));",
          "  --text-highlight-bg: \(rgba($c.accent.primary; 0.25));",
          "",
          "  --interactive-accent: \($c.accent.primary);",
          "  --interactive-accent-hover: \($c.accent.warning);",
          "  --link-color: \($c.accent.primary);",
          "  --link-color-hover: \($c.accent.warning);",
          "  --link-external-color: \($c.accent.primary);",
          "  --link-external-color-hover: \($c.accent.warning);",
          "",
          "  --text-success: \($c.accent.success);",
          "  --text-warning: \($c.accent.warning);",
          "  --text-error: \($c.accent.error);",
          "",
          "  --code-background: \($c.surface.raised);",
          "  --code-normal: \($c.text.primary);",
          "  --code-comment: \(tok("Comment"));",
          "  --code-keyword: \(tok("Keyword"));",
          "  --code-string: \(tok("String"));",
          "  --code-function: \(tok("Function"));",
          "  --code-value: \(tok("Number and constant"));",
          "  --code-property: \(tok("Property"));",
          "  --code-tag: \(tok("Tag"));",
          "  --code-punctuation: \(tok("Operator"));",
          "  --code-operator: \(tok("Operator"));",
          "  --code-important: \($c.accent.error);",
          "}"
    ' "$PALETTE" > "$dir/theme.css"
}

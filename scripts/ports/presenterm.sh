# shellcheck shell=bash
# presenterm slide themes plus the code highlighting theme each one names, per variant.
# Output: ports/presenterm/terminal-noir{,-paper}.yaml, ports/presenterm/terminal-noir{,-paper}.tmTheme

build_presenterm() {
    local v name
    for v in dark light; do
        name="terminal-noir$([ "$v" = light ] && echo -paper || true)"
        presenterm_theme "$v" "$name" > "$OUT/ports/presenterm/$name.yaml"
        presenterm_code "$v" "$name" > "$OUT/ports/presenterm/$name.tmTheme"
    done
}


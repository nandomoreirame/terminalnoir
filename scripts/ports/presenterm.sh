# Code highlighting (TextMate plist) on the raised surface, so a code block
# stands out from the slide background.
presenterm_code() {
    jq -r --arg v "$1" --arg name "$2" --slurpfile syn "$SYNTAX" '
        .variants[$v] as $c
        | def ref($p): $c | getpath($p | split("."));
          def kv($k; $x): "\t\t\t\t<key>\($k)</key>\n\t\t\t\t<string>\($x)</string>";
        [
            "<?xml version=\"1.0\" encoding=\"UTF-8\"?>",
            "<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">",
            "<!-- Terminal Noir for presenterm code blocks. https://terminalnoir.web.app -->",
            "<!-- Generated by scripts/build from palette/palette.json and palette/syntax.json. -->",
            "<plist version=\"1.0\">",
            "<dict>",
            "\t<key>name</key>",
            "\t<string>\($name)</string>",
            "\t<key>settings</key>",
            "\t<array>",
            "\t\t<dict>",
            "\t\t\t<key>settings</key>",
            "\t\t\t<dict>",
            kv("background"; $c.surface.raised),
            kv("foreground"; $c.text.primary),
            kv("caret"; $c.accent.primary),
            kv("selection"; $c.surface.selection),
            kv("lineHighlight"; $c.surface.elevated),
            kv("gutter"; $c.surface.raised),
            kv("gutterForeground"; $c.text.faint),
            "\t\t\t</dict>",
            "\t\t</dict>",
            ($syn[0].tokens[] | (
                "\t\t<dict>",
                "\t\t\t<key>name</key>",
                "\t\t\t<string>\(.name)</string>",
                "\t\t\t<key>scope</key>",
                "\t\t\t<string>\(.scope | join(", "))</string>",
                "\t\t\t<key>settings</key>",
                "\t\t\t<dict>",
                (if .color then kv("foreground"; ref(.color)) else empty end),
                (if .fontStyle then kv("fontStyle"; .fontStyle) else empty end),
                "\t\t\t</dict>",
                "\t\t</dict>"
            )),
            "\t</array>",
            "</dict>",
            "</plist>"
        ]
        | .[]' "$PALETTE"
}

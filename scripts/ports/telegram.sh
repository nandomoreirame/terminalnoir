# shellcheck shell=bash
# Telegram Desktop palettes and themes, one per variant. The key-to-name mapping
# lives in scripts/ports/telegram.keys; this defines the tn* names from the palette.
# A .tdesktop-theme is a zip of the palette (colors.tdesktop-theme) and the
# variant's wallpaper (background.png), with fixed dates so builds match.
# Output: ports/telegram/terminal-noir{,-paper}.tdesktop-palette and .tdesktop-theme

build_telegram() {
    local v name file keys wall
    keys="$(dirname "${BASH_SOURCE[0]}")/telegram.keys"
    for v in dark light; do
        name="terminal-noir$([ "$v" = light ] && echo -paper || true)"
        file="$name.tdesktop-palette"
        {
            jq -r --arg v "$v" '
                .variants[$v] as $c
                | def hex($x): $x | ascii_downcase;
                  def d($k; $x): "\($k): \(hex($x));";
                  def t($k; $x): "\($k)Transparent: \(hex($x))cc;";
                "// Terminal Noir (\($v)) for Telegram Desktop. https://terminalnoir.web.app",
                "// Generated by scripts/build from palette/palette.json and scripts/ports/telegram.keys.",
                "",
                d("tnBase"; $c.surface.base), t("tnBase"; $c.surface.base),
                d("tnMantle"; $c.surface.raised), t("tnMantle"; $c.surface.raised),
                d("tnCrust"; $c.surface.shadow), t("tnCrust"; $c.surface.shadow),
                "tnCrustShadow: \(hex($c.surface.shadow))11;",
                d("tnSurface0"; $c.surface.elevated), t("tnSurface0"; $c.surface.elevated),
                d("tnSurface1"; $c.surface.border), t("tnSurface1"; $c.surface.border),
                d("tnSurface2"; $c.surface.selection), t("tnSurface2"; $c.surface.selection),
                d("tnOverlay0"; $c.surface.outline),
                d("tnOverlay1"; $c.text.faint), t("tnOverlay1"; $c.text.faint),
                d("tnOverlay2"; $c.text.muted), t("tnOverlay2"; $c.text.muted),
                d("tnSubtext0"; $c.text.muted),
                d("tnSubtext1"; $c.text.muted),
                d("tnText"; $c.text.primary),
                d("tnAccent"; $c.accent.primary),
                d("tnPeach"; $c.accent.primary),
                d("tnGreen"; $c.accent.success),
                d("tnYellow"; $c.accent.warning),
                d("tnMaroon"; $c.accent.error),
                d("tnBlue"; $c.accent.info),
                d("tnRed"; $c.ansi.normal.red),
                d("tnFlamingo"; $c.ansi.bright.red),
                d("tnRosewater"; $c.ansi.bright.red), t("tnRosewater"; $c.ansi.bright.red),
                d("tnMauve"; $c.ansi.normal.magenta),
                d("tnPink"; $c.ansi.bright.magenta),
                d("tnLavender"; $c.ansi.bright.blue),
                d("tnSapphire"; $c.ansi.normal.blue),
                d("tnSky"; $c.ansi.bright.cyan),
                d("tnTeal"; $c.ansi.normal.cyan),
                ""' "$PALETTE"
            grep -v '^//' "$keys" | sed '/./,$!d'
        } > "$OUT/ports/telegram/$file"

        wall="$ROOT/assets/wallpapers/$([ "$v" = light ] && echo paper || echo noir).png"
        /usr/bin/python3 -I - "$OUT/ports/telegram/$name.tdesktop-theme" \
            "$OUT/ports/telegram/$file" "$wall" <<'PY'
import sys, zipfile

out, colors, background = sys.argv[1:4]
with zipfile.ZipFile(out, "w", zipfile.ZIP_STORED) as z:
    for arcname, path in (("colors.tdesktop-theme", colors), ("background.png", background)):
        info = zipfile.ZipInfo(arcname, date_time=(2026, 1, 1, 0, 0, 0))
        info.external_attr = 0o644 << 16
        info.create_system = 3
        with open(path, "rb") as f:
            z.writestr(info, f.read())
PY
    done
}

                "terminal.ansiBlue": $c.ansi.normal.blue,
                "terminal.ansiMagenta": $c.ansi.normal.magenta,
                "terminal.ansiCyan": $c.ansi.normal.cyan,
                "terminal.ansiWhite": $c.ansi.normal.white,

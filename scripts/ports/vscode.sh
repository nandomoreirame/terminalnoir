        publisher: "nandomoreira",
        license: "MIT",
        homepage: .homepage,
        engines: { vscode: "^1.70.0" },
        categories: ["Themes"],
        keywords: ["dark", "theme", "amber", "terminal noir"],
        contributes: { themes: [{
            label: "Terminal Noir",
            uiTheme: "vs-dark",
            path: "./themes/terminal-noir-color-theme.json"
        }] }
    }' "$PALETTE" > "$dir/package.json"

    jq --slurpfile syn "$SYNTAX" '
        .variants.dark as $c
        | def ref($p): $c | getpath($p | split("."));
        {

# shellcheck shell=bash
# zsh-syntax-highlighting and zsh-autosuggestions styles, one file per variant.
# Output: ports/zsh/terminal-noir.zsh, ports/zsh/terminal-noir-paper.zsh

build_zsh() {
    local v file
    for v in dark light; do
        file="terminal-noir$([ "$v" = light ] && echo -paper || true).zsh"
        jq -r --arg v "$v" --arg q "'" '
            .variants[$v] as $c
            | def fg($x): "fg=\($x)";
              def s($k; $style): "ZSH_HIGHLIGHT_STYLES[\($k)]=\($q)\($style)\($q)";
            "# Terminal Noir (\($v)) for zsh-syntax-highlighting and zsh-autosuggestions.",
            "# https://terminalnoir.web.app",
            "# Generated by scripts/build from palette/palette.json.",
            "# Source it from .zshrc; the order relative to the plugins does not matter.",
            "",
            "typeset -gA ZSH_HIGHLIGHT_STYLES",
            s("default"; "none"),
            s("unknown-token"; fg($c.accent.error)),
            s("reserved-word"; fg($c.accent.primary)),
            (["alias", "suffix-alias", "global-alias", "builtin", "function", "command", "hashed-command", "arg0"][]
                | s(.; fg($c.accent.info))),
            s("precommand"; fg($c.accent.info) + ",underline"),
            s("autodirectory"; fg($c.accent.info) + ",underline"),
            (["commandseparator", "redirection", "named-fd", "numeric-fd", "back-quoted-argument-delimiter",
              "command-substitution-delimiter", "process-substitution-delimiter", "arithmetic-expansion"][]
                | s(.; fg($c.accent.warning))),
            (["single-quoted-argument", "double-quoted-argument", "dollar-quoted-argument", "back-quoted-argument"][]
                | s(.; fg($c.accent.success))),
            (["back-double-quoted-argument", "back-dollar-quoted-argument", "rc-quote", "globbing", "history-expansion",
              "single-hyphen-option", "double-hyphen-option"][]
                | s(.; fg($c.ansi.bright.cyan))),
            s("dollar-double-quoted-argument"; fg($c.ansi.bright.magenta)),
            s("assign"; fg($c.ansi.bright.magenta)),
            s("path"; "underline"),
            s("path_prefix"; "underline"),
            s("comment"; fg($c.text.muted)),
            s("bracket-error"; fg($c.accent.error) + ",bold"),
            s("bracket-level-1"; fg($c.accent.primary)),
            s("bracket-level-2"; fg($c.accent.info)),
            s("bracket-level-3"; fg($c.ansi.bright.magenta)),
            s("bracket-level-4"; fg($c.accent.success)),
            s("cursor-matchingbracket"; "standout"),
            "",
            "ZSH_AUTOSUGGEST_HIGHLIGHT_STYLE=\($q)\(fg($c.text.faint))\($q)"' "$PALETTE" > "$OUT/ports/zsh/$file"
    done
}
